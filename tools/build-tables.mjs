// Writes src/data/tables.js: the lookup tables of Load Calculation V1.25 (no project or client data),
// so the app calculates without the master file. Run: node tools/build-tables.mjs /path/to/master.xlsx
import JSZip from 'jszip';
import { readFileSync, writeFileSync } from 'node:fs';
import { extractV125 } from '../src/data/fromMaster.js';
const d = await extractV125(JSZip, readFileSync(process.argv[2] || process.env.HLS_MASTER));
writeFileSync(new URL('../src/data/tables.js', import.meta.url), `// Lookup tables of Load Calculation V1.25 (psychrometric table, foods, insulation thickness,
// lighting, fan factor, door protection, ABF fan points). Generated by tools/build-tables.mjs.
// No project, client or job data. Used when no master file is loaded on the device.
export const BUILTIN = ${JSON.stringify(d)};
`);
console.log('tables.js written', JSON.stringify(d).length, 'bytes');
